android {
  namespace = "com.example"
  compileSdk { version = release(36) { minorApiLevel = 1 } }

  defaultConfig {
    applicationId = "com.aistudio.wpsoffice.oxfld"
    minSdk = 24
    targetSdk = 36
    versionCode = 1
    versionName = "1.0"

    testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
  }

  signingConfigs {
    // The upload keystore is a secret and is never committed. When it is absent
    // (a fresh clone, CI without secrets) the release build still assembles an
    // unsigned APK instead of failing the task graph on a missing file.
    val uploadKeystore = System.getenv("KEYSTORE_PATH")?.let { file(it) }
      ?: file("${rootDir}/my-upload-key.jks").takeIf { it.exists() }
    if (uploadKeystore != null) {
      create("release") {
        storeFile = uploadKeystore
        storePassword = System.getenv("STORE_PASSWORD")
        keyAlias = "upload"
        keyPassword = System.getenv("KEY_PASSWORD")
      }
    }
    create("debugConfig") {
      storeFile = file("${rootDir}/debug.keystore")
      storePassword = "android"
      keyAlias = "androiddebugkey"
      keyPassword = "android"
    }
  }

  buildTypes {
    release {
      isCrunchPngs = false
      // R8 code shrinking + resource shrinking (OPTIMIZE_PERFORMANCE.md §7)
      isMinifyEnabled = true
      isShrinkResources = true
      proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
      // null when no upload keystore is configured → unsigned release APK
      signingConfig = signingConfigs.findByName("release")
    }
    debug { signingConfig = signingConfigs.getByName("debugConfig") }
    // Allow Perfetto/CPU profiling of release builds on test devices
    // (DEEP_OPTIMIZATION_ANDROID17_PIXEL7A.md §2.3)
    create("benchmark") {
      initWith(getByName("release"))
      matchingFallbacks.add("release")
      isDebuggable = false
      isProfileable = true
      signingConfig = signingConfigs.getByName("debugConfig")
    }
  }
  compileOptions {
    sourceCompatibility = JavaVersion.VERSION_11
    targetCompatibility = JavaVersion.VERSION_11
  }
  buildFeatures {
    compose = true
    buildConfig = true
  }
  testOptions { unitTests { isIncludeAndroidResources = true } }
  dependenciesInfo {
    includeInApk = false
    includeInBundle = true
  }
}

